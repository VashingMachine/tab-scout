import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = new URL("../SafariExtension/overlay.js", import.meta.url);
const result = await build({
  absWorkingDir: root,
  entryPoints: ["SafariExtension/overlay-entry.mjs"],
  outfile: "SafariExtension/overlay.js",
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["safari17"],
  loader: { ".html": "text", ".css": "text", ".svg": "text" },
  charset: "ascii",
  legalComments: "inline",
  banner: { js: "// Generated by npm run build:overlay. Edit overlay-entry.mjs and its imports." },
  write: false,
});
const contents = result.outputFiles[0].contents;
if (process.argv.includes("--check")) {
  const existing = await readFile(output);
  if (!existing.equals(Buffer.from(contents))) {
    throw new Error("overlay.js is stale. Run npm run build:overlay and commit the result.");
  }
  console.log("Overlay bundle matches its source.");
} else {
  await writeFile(output, contents);
  console.log("Built self-contained Safari overlay.");
}
